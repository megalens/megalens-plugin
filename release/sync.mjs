import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = (name) => readFileSync(path.join(root, name), 'utf8');
const check = process.argv.includes('--check');
const stale = [];

function sync(name, content) {
  const destination = path.join(root, name);
  try {
    if (read(name) === content) return;
  } catch (err) {
    if (err.code !== 'ENOENT') throw err;
  }
  if (check) {
    stale.push(name);
    return;
  }
  mkdirSync(path.dirname(destination), { recursive: true });
  writeFileSync(destination, content);
}

const pins = JSON.parse(read('release/pins.json'));
const placeholders = { ENGINE_VERSION: pins.engine };
for (const [key, { sha, tag }] of Object.entries(pins.actions)) {
  if (!/^[a-f0-9]{40}$/.test(sha)) throw new Error(`Invalid commit pin for ${key}`);
  placeholders[`${key}_SHA`] = sha;
  placeholders[`${key}_TAG`] = tag;
}
const workflow = '# Generated by npm run sync:release.\n'
  + read('release/megalens-dispatch.yml.in').replace(/@([A-Z_]+)@/g, (_, key) => {
    if (!Object.hasOwn(placeholders, key)) throw new Error(`Missing workflow pin ${key}`);
    return placeholders[key];
  });
for (const prefix of ['', 'claude/', 'codex/runtime/', 'cursor/']) {
  sync(`${prefix}templates/megalens-dispatch.yml`, workflow);
}

for (const name of [
  'package.json', '.claude-plugin/plugin.json', 'codex/.codex-plugin/plugin.json',
  'cursor/package.json', 'cursor/.cursor-plugin/plugin.json',
]) {
  const manifest = JSON.parse(read(name));
  if (manifest.version !== pins.version) {
    manifest.version = pins.version;
    sync(name, JSON.stringify(manifest, null, 2) + '\n');
  }
}
const marketplacePath = '.cursor-plugin/marketplace.json';
const marketplace = JSON.parse(read(marketplacePath));
const cursorEntry = marketplace.plugins.find(({ name }) => name === 'megalens');
if (marketplace.metadata.version !== pins.version || cursorEntry.version !== pins.version) {
  marketplace.metadata.version = pins.version;
  cursorEntry.version = pins.version;
  sync(marketplacePath, JSON.stringify(marketplace, null, 2) + '\n');
}

// Claude Code installs only the selected plugin directory. Keep the original
// root entry points working and ship their runtime in the standalone directory.
const claudeFiles = [
  '.mcp.json', 'LICENSE', 'scripts/collect.mjs', 'scripts/engine.mjs',
  'scripts/mcp-server.mjs', 'scripts/lib/engine-core.mjs', 'scripts/lib/gh-runner.mjs',
  'scripts/lib/latest-review.mjs', 'scripts/lib/local-standard.mjs',
  'scripts/lib/safety.mjs', 'scripts/lib/wait-loop.mjs',
  ...readdirSync(path.join(root, 'commands')).filter((name) => name.endsWith('.md')).map((name) => `commands/${name}`),
];
for (const name of claudeFiles) sync(`claude/${name}`, read(name));
const claudeManifest = JSON.parse(read('.claude-plugin/plugin.json'));
claudeManifest.version = pins.version;
sync('claude/.claude-plugin/plugin.json', JSON.stringify(claudeManifest, null, 2) + '\n');

if (stale.length) {
  console.error('Run npm run sync:release to update these files:\n' + stale.join('\n'));
  process.exitCode = 1;
}
